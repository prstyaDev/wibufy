import type { Expr, Stmt, TypeRef } from "./ast.js";

/** Emits executable ECMAScript from Wibufy's already-resolved AST. */
export class JavaScriptCodeGenerator {
  private indentation = 0;
  private temporary = 0;
  private aliases = new Map<string, Extract<Stmt, { kind: "typeAlias" }>>();

  generate(program: Stmt[]): string {
    this.indentation = 0;
    this.temporary = 0;
    this.aliases = new Map(program.filter((statement): statement is Extract<Stmt, { kind: "typeAlias" }> => statement.kind === "typeAlias").map(statement => [statement.name, statement]));
    const body = program.map(statement => this.statement(statement)).filter(Boolean).join("\n");
    return [
      "// Generated by the Wibufy JavaScript compiler. Do not edit by hand.",
      "import * as __wibufyFs from 'node:fs';",
      "",
      this.runtime(),
      "",
      body,
      "",
    ].join("\n");
  }

  private runtime(): string {
    return [
      "function __wibufyStringify(value) {",
      "  if (value === null) return 'null';",
      "  if (Array.isArray(value)) return `[${value.map(__wibufyStringify).join(', ')}]`;",
      "  if (typeof value === 'object') return `{ ${Object.entries(value).map(([key, item]) => `${key}: ${__wibufyStringify(item)}`).join(', ')} }`;",
      "  return String(value);",
      "}",
      "function __wibufyPrint(value) { console.log(__wibufyStringify(value)); }",
      "function __wibufyTruthy(value) { return value !== false && value !== null; }",
      "function __wibufyDivide(left, right) { if (right === 0) throw new Error('Division by zero.'); return left / right; }",
      "function __wibufyModulo(left, right) { if (right === 0) throw new Error('Division by zero.'); return left % right; }",
      "function __wibufyAssertArray(value) { if (!Array.isArray(value)) throw new Error('for-in requires an array.'); if (value.length > 100000) throw new Error('Loop safety limit exceeded (100000 iterations).'); return value; }",
      "function __wibufyGetProperty(target, name) {",
      "  if (target === null || typeof target !== 'object' || (Array.isArray(target) && name !== 'length')) throw new Error(`Cannot read property '${name}' from this value.`);",
      "  if (!(name in target)) throw new Error(`Object has no property '${name}'.`); return target[name];",
      "}",
      "function __wibufySetProperty(target, name, value) {",
      "  if (target === null || typeof target !== 'object' || Array.isArray(target)) throw new Error(`Cannot assign property '${name}' on this value.`);",
      "  if (!(name in target)) throw new Error(`Object has no property '${name}'.`); target[name] = value; return value;",
      "}",
      "function __wibufyArrayPush(target, args) {",
      "  if (target !== null && typeof target === 'object' && !Array.isArray(target) && Object.prototype.hasOwnProperty.call(target, 'push')) {",
      "    const callable = target.push; if (typeof callable !== 'function') throw new Error(\"Property 'push' is not callable.\"); return callable(...args);",
      "  }",
      "  if (!Array.isArray(target)) throw new Error(\"Array method 'push' requires an array receiver.\");",
      "  if (args.length !== 1) throw new Error(\"Invalid arguments for array method 'push'.\");",
      "  target.push(args[0]); return target.length;",
      "}",
      "function __wibufyCallStringMethod(target, name, args) {",
      "  if (target !== null && typeof target === 'object' && !Array.isArray(target) && Object.prototype.hasOwnProperty.call(target, name)) {",
      "    const callable = target[name]; if (typeof callable !== 'function') throw new Error(`Property '${name}' is not callable.`);",
      "    return callable(...args);",
      "  }",
      "  if (typeof target !== 'string') throw new Error(`Method '${name}' requires a string or object receiver.`);",
      "  switch (name) {",
      "    case 'toUpperCase': if (args.length === 0) return target.toUpperCase(); break;",
      "    case 'toLowerCase': if (args.length === 0) return target.toLowerCase(); break;",
      "    case 'trim': if (args.length === 0) return target.trim(); break;",
      "    case 'includes': if (args.length === 1 && typeof args[0] === 'string') return target.includes(args[0]); break;",
      "    case 'startsWith': if (args.length === 1 && typeof args[0] === 'string') return target.startsWith(args[0]); break;",
      "    case 'endsWith': if (args.length === 1 && typeof args[0] === 'string') return target.endsWith(args[0]); break;",
      "    case 'indexOf': if (args.length === 1 && typeof args[0] === 'string') return target.indexOf(args[0]); break;",
      "    case 'replace': if (args.length === 2 && typeof args[0] === 'string' && typeof args[1] === 'string') return target.replace(args[0], args[1]); break;",
      "    default: throw new Error(`Unknown string method '${name}'.`);",
      "  }",
      "  throw new Error(`Invalid arguments for string method '${name}'.`);",
      "}",
      "function __wibufyGetIndex(target, index) {",
      "  if (!Array.isArray(target)) throw new Error('Index access requires an array.');",
      "  if (!Number.isInteger(index) || index < 0 || index >= target.length) throw new Error(`Array index ${String(index)} is out of bounds.`);",
      "  return target[index];",
      "}",
      "function __wibufySetIndex(target, index, value) {",
      "  if (!Array.isArray(target)) throw new Error('Index assignment requires an array.');",
      "  if (!Number.isInteger(index) || index < 0 || index >= target.length) throw new Error(`Array index ${String(index)} is out of bounds.`);",
      "  target[index] = value; return value;",
      "}",
      "function __wibufyReadLine() {",
      "  const bytes = []; const buffer = Buffer.alloc(1);",
      "  while (true) { const count = __wibufyFs.readSync(0, buffer, 0, 1, null);",
      "    if (!count) return bytes.length ? Buffer.from(bytes).toString('utf8') : null;",
      "    if (buffer[0] === 10) return Buffer.from(bytes).toString('utf8').replace(/\\r$/, '');",
      "    bytes.push(buffer[0]);",
      "  }",
      "}",
    ].join("\n");
  }

  private pad(): string { return "  ".repeat(this.indentation); }
  /** Encode source names to avoid JavaScript reserved words and runtime helper collisions. */
  private identifier(name: string): string {
    const encoded = Array.from(name, character => character.codePointAt(0)!.toString(16)).join("_");
    return `__wibufyUser_${encoded || "empty"}`;
  }
  private block(statements: Stmt[]): string {
    this.indentation++;
    const body = statements.map(statement => this.statement(statement)).filter(Boolean).join("\n");
    this.indentation--;
    return `{${body ? `\n${body}\n${this.pad()}` : ""}}`;
  }

  private statement(statement: Stmt): string {
    const pad = this.pad();
    switch (statement.kind) {
      case "import":
      case "typeAlias":
        return "";
      case "var":
        return `${pad}${statement.mutable ? "let" : "const"} ${this.identifier(statement.name)} = ${this.expression(statement.initializer)};`;
      case "function":
        if (statement.native) return `${pad}${this.nativeFunction(statement.name, statement.native, statement.params.map(parameter => parameter.name))}`;
        return `${pad}function ${this.identifier(statement.name)}(${statement.params.map(parameter => this.identifier(parameter.name)).join(", ")}) ${this.block([...statement.body, { kind: "return", value: { kind: "literal", value: null } }])}`;
      case "return":
        return `${pad}return ${statement.value ? this.expression(statement.value) : "null"};`;
      case "print":
        return `${pad}__wibufyPrint(${this.expression(statement.expression)});`;
      case "expression":
        return `${pad}${this.expression(statement.expression)};`;
      case "block":
        return `${pad}${this.block(statement.statements)}`;
      case "if":
        return `${pad}if (__wibufyTruthy(${this.expression(statement.condition)})) ${this.statementAsBlock(statement.thenBranch)}${statement.elseBranch ? ` else ${this.statementAsBlock(statement.elseBranch)}` : ""}`;
      case "while": {
        const counter = `__wibufyLoop${this.temporary++}`;
        return `${pad}{\n${pad}  let ${counter} = 0;\n${pad}  while (__wibufyTruthy(${this.expression(statement.condition)})) {\n${pad}    if (++${counter} > 100000) throw new Error('Loop safety limit exceeded (100000 iterations).');\n${this.indentedStatement(statement.body, 2)}\n${pad}  }\n${pad}}`;
      }
      case "forIn": {
        const counter = `__wibufyLoop${this.temporary++}`;
        const item = `__wibufyItem${this.temporary++}`;
        return `${pad}{\n${pad}  let ${counter} = 0;\n${pad}  for (const ${item} of __wibufyAssertArray(${this.expression(statement.iterable)})) {\n${pad}    if (++${counter} > 100000) throw new Error('Loop safety limit exceeded (100000 iterations).');\n${pad}    const ${this.identifier(statement.name)} = ${item};\n${this.indentedStatement(statement.body, 2)}\n${pad}  }\n${pad}}`;
      }
    }
  }

  private statementAsBlock(statement: Stmt): string {
    return statement.kind === "block" ? this.block(statement.statements) : this.block([statement]);
  }

  private indentedStatement(statement: Stmt, extra: number): string {
    const previous = this.indentation;
    this.indentation += extra;
    const result = this.statement(statement);
    this.indentation = previous;
    return result;
  }

  private resolvePrimitiveType(ref: TypeRef, substitutions = new Map<string, TypeRef>(), seen = new Set<string>()): string | null {
    if (typeof ref === "string") return ref === "number" || ref === "string" || ref === "boolean" || ref === "null" ? ref : null;
    if (ref.kind !== "namedType") return null;
    if (ref.arguments.length === 0 && substitutions.has(ref.name)) return this.resolvePrimitiveType(substitutions.get(ref.name)!, substitutions, seen);
    if (["number", "string", "boolean", "null"].includes(ref.name)) return ref.arguments.length === 0 ? ref.name : null;
    const alias = this.aliases.get(ref.name);
    if (!alias || seen.has(ref.name) || alias.typeParameters.length !== ref.arguments.length) return null;
    const next = new Map<string, TypeRef>();
    alias.typeParameters.forEach((parameter, index) => next.set(parameter.name, ref.arguments[index]!));
    const visited = new Set(seen);
    visited.add(ref.name);
    return this.resolvePrimitiveType(alias.target, next, visited);
  }

  private nativeFunction(name: string, native: string, parameters: string[]): string {
    const args = parameters.map(parameter => this.identifier(parameter));
    let body: string;
    switch (native) {
      case "wibufy/fs.readText": body = `return __wibufyFs.readFileSync(${args[0]}, 'utf8');`; break;
      case "wibufy/fs.writeText": body = `__wibufyFs.writeFileSync(${args[0]}, ${args[1]}, 'utf8'); return null;`; break;
      case "wibufy/fs.exists": body = `return __wibufyFs.existsSync(${args[0]});`; break;
      case "wibufy/fs.listDir": body = `return __wibufyFs.readdirSync(${args[0]});`; break;
      case "wibufy/json.parse": body = `return JSON.parse(${args[0]});`; break;
      case "wibufy/json.stringify": body = `const result = JSON.stringify(${args[0]}); if (result === undefined) throw new Error('json.stringify cannot serialize this value.'); return result;`; break;
      case "wibufy/string.trim": body = `return ${args[0]}.trim();`; break;
      case "wibufy/string.split": body = `return ${args[0]}.split(${args[1]});`; break;
      case "wibufy/string.join": body = `return ${args[0]}.join(${args[1]});`; break;
      case "wibufy/string.replace": body = `return ${args[0]}.replaceAll(${args[1]}, ${args[2]});`; break;
      case "wibufy/math.abs": body = `return Math.abs(${args[0]});`; break;
      case "wibufy/math.sqrt": body = `return Math.sqrt(${args[0]});`; break;
      case "wibufy/math.floor": body = `return Math.floor(${args[0]});`; break;
      case "wibufy/math.ceil": body = `return Math.ceil(${args[0]});`; break;
      case "wibufy/math.round": body = `return Math.round(${args[0]});`; break;
      case "wibufy/math.pow": body = `return Math.pow(${args[0]}, ${args[1]});`; break;
      case "wibufy/datetime.now": body = "return Date.now();"; break;
      case "wibufy/datetime.parse": body = `const parsed = Date.parse(${args[0]}); if (Number.isNaN(parsed)) throw new Error('Invalid date/time string.'); return parsed;`; break;
      case "wibufy/datetime.toISOString": body = `const date = new Date(${args[0]}); if (Number.isNaN(date.getTime())) throw new Error('Invalid timestamp.'); return date.toISOString();`; break;
      case "wibufy/io.readLine": body = "return __wibufyReadLine();"; break;
      case "wibufy/io.write": body = `process.stdout.write(String(${args[0]})); return null;`; break;
      case "wibufy/io.writeLine": body = `process.stdout.write(String(${args[0]}) + '\\n'); return null;`; break;
      default: throw new Error(`[Wibufy Compiler Error] Unsupported native function '${native}' (${name}).`);
    }
    return `function ${this.identifier(name)}(${parameters.map(parameter => this.identifier(parameter)).join(", ")}) { ${body} }`;
  }

  private expression(expression: Expr): string {
    switch (expression.kind) {
      case "literal": return expression.value === null ? "null" : JSON.stringify(expression.value);
      case "typeTest": {
        const value = this.expression(expression.value);
        const type = this.resolvePrimitiveType(expression.type);
        const temporary = `__wibufyTypeValue${this.temporary++}`;
        if (type === "null") return `((${temporary}) => ${temporary} === null)(${value})`;
        if (type === "number") return `((${temporary}) => typeof ${temporary} === 'number' && !Number.isNaN(${temporary}))(${value})`;
        if (type === "string" || type === "boolean") return `((${temporary}) => typeof ${temporary} === ${JSON.stringify(type)})(${value})`;
        throw new Error("[Wibufy Compiler Error] Runtime type guards currently support primitive aliases only.");
      }
      case "variable": return this.identifier(expression.name);
      case "grouping": return `(${this.expression(expression.expression)})`;
      case "unary": return `(${expression.operator}${this.expression(expression.right)})`;
      case "binary": {
        const left = this.expression(expression.left);
        const right = this.expression(expression.right);
        if (expression.operator === "and") return `(__wibufyTruthy(${left}) ? __wibufyTruthy(${right}) : false)`;
        if (expression.operator === "or") return `(__wibufyTruthy(${left}) ? true : __wibufyTruthy(${right}))`;
        if (expression.operator === "/") return `__wibufyDivide(${left}, ${right})`;
        if (expression.operator === "%") return `__wibufyModulo(${left}, ${right})`;
        return `(${left} ${expression.operator} ${right})`;
      }
      case "assign": return `(${this.identifier(expression.name)} = ${this.expression(expression.value)})`;
      case "index": return `__wibufyGetIndex(${this.expression(expression.object)}, ${this.expression(expression.index)})`;
      case "indexAssign": return `__wibufySetIndex(${this.expression(expression.object)}, ${this.expression(expression.index)}, ${this.expression(expression.value)})`;
      case "property": return `__wibufyGetProperty(${this.expression(expression.object)}, ${JSON.stringify(expression.name)})`;
      case "propertyAssign": return `__wibufySetProperty(${this.expression(expression.object)}, ${JSON.stringify(expression.name)}, ${this.expression(expression.value)})`;
      case "array": return `[${expression.elements.map(element => this.expression(element)).join(", ")}]`;
      case "object": return `Object.assign(Object.create(null), Object.fromEntries([${expression.properties.map(property => `[${JSON.stringify(property.name)}, ${this.expression(property.value)}]`).join(", ")}]))`;
      case "call": {
        if (expression.callee.kind === "property") {
          if (expression.callee.name === "push") {
            return `__wibufyArrayPush(${this.expression(expression.callee.object)}, [${expression.args.map(argument => this.expression(argument)).join(", ")}])`;
          }
          return `__wibufyCallStringMethod(${this.expression(expression.callee.object)}, ${JSON.stringify(expression.callee.name)}, [${expression.args.map(argument => this.expression(argument)).join(", ")}])`;
        }
        if (expression.callee.kind !== "variable") throw new Error("[Wibufy Compiler Error] Only named function calls and supported methods are allowed.");
        return `${this.expression(expression.callee)}(${expression.args.map(argument => this.expression(argument)).join(", ")})`;
      }
    }
  }
}
